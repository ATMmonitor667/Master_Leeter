import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const require = createRequire(resolve('apps/web/package.json'));
const { default: StyleDictionary } = await import(pathToFileURL(require.resolve('style-dictionary')).href);
const source = JSON.parse(readFileSync('design/tokens/semantic.json', 'utf8'));
const check = process.argv.includes('--check');
function emit(path, content) {
  if (check) { if (readFileSync(path, 'utf8') !== content) throw new Error(`Token drift: ${path}`); }
  else writeFileSync(path, content);
}
StyleDictionary.registerFormat({ name: 'master/css', format: ({ dictionary }) => {
  const props = dictionary.allTokens.map(t => `  --${t.path.join('-')}: ${t.$value ?? t.value};`).join('\n');
  return `/* Generated by pnpm tokens. Edit design/tokens/semantic.json. */\n@layer tokens {\n:root {\n${props}\n}\n}\n`;
}});
const sd = new StyleDictionary({ tokens: source, platforms: { css: { transforms: [], files: [{ destination: 'tokens.css', format: 'master/css' }] } } });
const result = await sd.formatPlatform('css');
emit('apps/web/app/styles/tokens.css', result[0].output);
const colors = Object.fromEntries(Object.entries(source).filter(([,v]) => v.$type === 'color').map(([k,v]) => {
  const [,light,dark] = /light-dark\(([^,]+), ([^)]+)\)/.exec(v.$value);
  return [k,{light,dark}];
}));
emit('apps/web/lib/tokens.ts', `// Generated by pnpm tokens.\nexport const colors = ${JSON.stringify(colors,null,2)} as const;\n`);
emit('apps/web/lib/monaco-theme.ts', `// Generated by pnpm tokens.\nimport { colors } from './tokens';\nexport function editorTheme(dark: boolean) {\n  const mode = dark ? 'dark' : 'light';\n  return { base: dark ? 'vs-dark' as const : 'vs' as const, inherit: true, rules: [{token: 'comment', foreground: colors.muted[mode].slice(1)}, {token: 'keyword', foreground: colors.accent[mode].slice(1)}, {token: 'string', foreground: colors.ok[mode].slice(1)}, {token: 'number', foreground: colors.warn[mode].slice(1)}], colors: { 'editor.background': colors['bg-soft'][mode], 'editor.foreground': colors.text[mode], 'editorLineNumber.foreground': colors.muted[mode], 'editor.selectionBackground': colors['blue-soft'][mode], 'editorCursor.foreground': colors.accent[mode] } };\n}\n`);
function luminance(hex) { const c=hex.slice(1).match(/../g).map(v=>parseInt(v,16)/255).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4); return c[0]*.2126+c[1]*.7152+c[2]*.0722; }
function contrast(a,b) { const l=[luminance(a),luminance(b)].sort((x,y)=>y-x); return (l[0]+.05)/(l[1]+.05); }
for(const mode of ['light','dark']) for(const surface of ['bg','bg-soft','panel','panel-raised']) {
  for(const [fg,min] of [['text',7],['muted',4.5],['muted-strong',4.5],['accent',4.5],['blue',4.5],['ok',4.5],['warn',4.5],['err',4.5],['border',3],['focus',3]]) {
    const ratio=contrast(colors[fg][mode],colors[surface][mode]);
    if(ratio<min) throw new Error(`${mode} ${fg} / ${surface}: ${ratio.toFixed(2)} < ${min}`);
  }
}
console.log(`Tokens ${check?'checked':'generated'}; both themes pass semantic contrast checks.`);
